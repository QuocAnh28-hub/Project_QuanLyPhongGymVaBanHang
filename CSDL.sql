CREATE DATABASE IF NOT EXISTS gym_management

USE gym_management;

CREATE TABLE TaiKhoan (
    TaiKhoanID INT AUTO_INCREMENT PRIMARY KEY,
    Email VARCHAR(100) NOT NULL UNIQUE,
    MatKhau VARCHAR(255) NOT NULL,
    VaiTro ENUM('CUSTOMER', 'STAFF', 'ADMIN') NOT NULL DEFAULT 'CUSTOMER',
    TrangThai ENUM('ACTIVE', 'LOCKED') NOT NULL DEFAULT 'ACTIVE',
    NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE HoiVien (
    HoiVienID INT AUTO_INCREMENT PRIMARY KEY,
    TaiKhoanID INT NOT NULL UNIQUE,
    HoTen VARCHAR(100) NOT NULL,
    NgaySinh DATE NULL,
    GioiTinh ENUM('NAM', 'NU', 'KHAC') NULL,
    SoDienThoai VARCHAR(20) NULL,
    Email VARCHAR(100) NULL,
    DiaChi VARCHAR(255) NULL,
    AnhDaiDien VARCHAR(255) NULL,
    NgayDangKy DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    TrangThai ENUM('ACTIVE', 'INACTIVE', 'BLOCKED') NOT NULL DEFAULT 'ACTIVE',

    CONSTRAINT FK_HoiVien_TaiKhoan
        FOREIGN KEY (TaiKhoanID)
        REFERENCES TaiKhoan(TaiKhoanID)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE NhanVien (
    NhanVienID INT AUTO_INCREMENT PRIMARY KEY,
    TaiKhoanID INT NOT NULL UNIQUE,
    HoTen VARCHAR(100) NOT NULL,
    NgaySinh DATE NULL,
    GioiTinh ENUM('NAM', 'NU', 'KHAC') NULL,
    SoDienThoai VARCHAR(20) NULL,
    Email VARCHAR(100) NULL,
    ChucVu VARCHAR(100) NULL,
    NgayVaoLam DATE NULL,
    TrangThai ENUM('ACTIVE', 'INACTIVE', 'BLOCKED') NOT NULL DEFAULT 'ACTIVE',

    CONSTRAINT FK_NhanVien_TaiKhoan
        FOREIGN KEY (TaiKhoanID)
        REFERENCES TaiKhoan(TaiKhoanID)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE TABLE GoiTap (
    GoiTapID INT AUTO_INCREMENT PRIMARY KEY,
    TenGoi VARCHAR(100) NOT NULL,
    MoTa TEXT NULL,
    ThoiHan INT NOT NULL COMMENT 'Số ngày sử dụng',
    Gia DECIMAL(15,2) NOT NULL DEFAULT 0,
    TrangThai ENUM('ACTIVE', 'INACTIVE') NOT NULL DEFAULT 'ACTIVE',
    NgayTao DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE DangKyGoiTap (
    DangKyID INT AUTO_INCREMENT PRIMARY KEY,
    HoiVienID INT NOT NULL,
    GoiTapID INT NOT NULL,
    NgayDangKy DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    NgayBatDau DATE NOT NULL,
    NgayKetThuc DATE NOT NULL,
    GiaThanhToan DECIMAL(15,2) NOT NULL DEFAULT 0,
    TrangThai ENUM('PENDING', 'ACTIVE', 'EXPIRED', 'CANCELLED') 
        NOT NULL DEFAULT 'PENDING',

    CONSTRAINT FK_DangKyGoiTap_HoiVien
        FOREIGN KEY (HoiVienID)
        REFERENCES HoiVien(HoiVienID)
        ON DELETE RESTRICT
        ON UPDATE CASCADE,

    CONSTRAINT FK_DangKyGoiTap_GoiTap
        FOREIGN KEY (GoiTapID)
        REFERENCES GoiTap(GoiTapID)
        ON DELETE RESTRICT
        ON UPDATE CASCADE
);

CREATE TABLE MaQR (
    MaQRID INT AUTO_INCREMENT PRIMARY KEY,
