CREATE TABLE PT (
    PTID INT AUTO_INCREMENT PRIMARY KEY,
    HoTen VARCHAR(100) NOT NULL,
    NgaySinh DATE NULL,
    GioiTinh ENUM('NAM', 'NU', 'KHAC') NULL,
