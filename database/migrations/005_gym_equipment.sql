CREATE TABLE IF NOT EXISTS maytap (
  MayTapID INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  MaMay VARCHAR(60) NOT NULL UNIQUE,
  TenMay VARCHAR(150) NOT NULL,
  NhomMay ENUM('CARDIO','STRENGTH','MULTI') NOT NULL DEFAULT 'STRENGTH',
  NhomCo VARCHAR(200) NOT NULL DEFAULT '',
  MoTa TEXT NOT NULL,
  HinhAnh VARCHAR(255) NULL,
  SoLuong INT NOT NULL DEFAULT 1,
  ViTri VARCHAR(150) NOT NULL DEFAULT '',
  TrangThai ENUM('ACTIVE','MAINTENANCE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
  NgayTao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  NgayCapNhat TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_maytap_status_group (TrangThai, NhomMay),
  CONSTRAINT chk_maytap_quantity CHECK (SoLuong >= 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
